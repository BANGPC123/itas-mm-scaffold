"""Build M8 table from render summaries and gate files. Every number comes from a file listed in the Source column."""
import json
from pathlib import Path
R = Path('output/demo_20261114/M8')
runs = [
    ('HEAD before M8 (profiled), night 90 s', 'before_night', 'night'),
    ('HEAD before M8 (profiled, repeat), night 90 s', 'before_night_r2', 'night'),
    ('M8.0 two instances, night 90 s', 'm80_twoinstance', 'night'),
    ('M8.1 rectangle overlay, night 90 s', 'm81_draw', 'night'),
    ('M8.2 FP16 COCO, night 90 s (rejected)', 'm82_half', 'night'),
    ('M8.1 rectangle overlay, demo video (pre-3c)', 'm8_demo', 'demo'),
    ('M8.3c detect every 2nd sample, night 90 s', 'm83c_night', 'night'),
    ('M8.3c detect every 2nd sample, demo video', 'm83c_demo', 'demo'),
]
lines = ['| Run | Wall s (summary) | Forward detect s (calls) | Overlay s | Forward alerts | nguy_co alerts | Alerts/min | Sign boxes vs M1 (mismatch samples) | Source |',
         '|---|---|---|---|---|---|---|---|---|']
for label, folder, clip in runs:
    base = R / folder
    s = json.loads((base / 'render' / 'summary.json').read_text(encoding='utf8'))
    p = s.get('profile_s', {})
    alerts = s['forward_warning']['alerts']
    nguy = sum(1 for a in alerts if a['level'] == 'nguy_co')
    minutes = s['output_frames'] / s['output_fps'] / 60
    gate_path = base / 'gate_vs_M1.json'
    mism = json.loads(gate_path.read_text(encoding='utf8'))['box_label_mismatch_count'] if gate_path.exists() else 'n/a'
    lines.append(f"| {label} | {s['elapsed_seconds']:.1f} | {p.get('fw_detect_s', 0):.2f} ({p.get('fw_detect_calls', 0)}) | {p.get('fw_draw_s', 0):.2f} | {len(alerts)} | {nguy} | {len(alerts)/minutes:.1f} | {mism} | {base.as_posix()}/render/summary.json |")
(R / 'M8_TABLE.md').write_text('# M8 measurements (generated by make_m8_table.py)\n\n' + '\n'.join(lines) + '\n', encoding='utf8')
print('\n'.join(lines))
